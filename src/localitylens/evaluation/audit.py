"""The 50-record feasibility audit: sample, annotation worksheet, and a rules-baseline run.

Sampling is per duplicate-locality group, not per specimen: a curator georeferences each
distinct locality once, so a frequent label ("Boulder.") counts once. Groups are ordered by
``sha256(seed | group_key)``, which is reproducible from the snapshot and the seed alone.

Order of work: the owner annotates ``worksheet.csv`` first, then opens the rules report.
Audited records (and their groups) must be assigned to the dev split, never to test.
"""

from __future__ import annotations

import csv
import hashlib
import json
import time
from collections import Counter
from collections.abc import Callable, Iterable
from pathlib import Path
from typing import TYPE_CHECKING, Any, Final

from pydantic import BaseModel, ConfigDict

from localitylens.gazetteer.index import Gazetteer
from localitylens.ingest.specimens import SpecimenRecord

if TYPE_CHECKING:
    from localitylens.extract.llm_client import ModelClient
    from localitylens.extract.schema import Interpretation
    from localitylens.geo.extents import ExtentStore
    from localitylens.pipeline.interpret import Extractor
    from localitylens.release import ReleaseManifest

AUDIT_VERSION: Final = "1"
WORKSHEET_COLUMNS: Final = (
    "audit_id", "gbif_id", "county", "locality",
    # filled in by the annotator, before looking at any system output:
    "description_type", "supported", "reference_features", "acceptable_gnis_ids",
    "distance", "unit", "direction", "qualifiers", "missing_information", "notes",
)  # fmt: skip


class AuditItem(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)
    audit_id: str
    group_size: int  # specimens in the snapshot sharing this locality group
    record: SpecimenRecord


class AuditSample(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)
    audit_version: str = AUDIT_VERSION
    snapshot_id: str
    screen_version: str
    grouping_version: str
    seed: str
    eligible_records: int
    eligible_groups: int
    items: tuple[AuditItem, ...]
    # Stratified dev samples only (omitted from the audit file, which predates them):
    name: str | None = None
    shape_version: str | None = None
    strata: dict[str, int] | None = None  # quota per text shape
    excluded_viewed_groups: int | None = None  # groups skipped because already viewed


def _rank(seed: str, key: str) -> str:
    return hashlib.sha256(f"{seed}|{key}".encode()).hexdigest()


def sample_groups(
    records: Iterable[SpecimenRecord], n: int, seed: str
) -> tuple[list[AuditItem], int, int]:
    """``n`` groups by seeded hash order; each represented by its lowest gbifID record."""
    representative: dict[str, SpecimenRecord] = {}
    sizes: Counter[str] = Counter()
    total = 0
    for record in records:
        total += 1
        sizes[record.group_key] += 1
        current = representative.get(record.group_key)
        if current is None or int(record.gbif_id) < int(current.gbif_id):
            representative[record.group_key] = record
    chosen = sorted(representative, key=lambda k: _rank(seed, k))[:n]
    items = [
        AuditItem(audit_id=f"A{i:02d}", group_size=sizes[k], record=representative[k])
        for i, k in enumerate(chosen, start=1)
    ]
    return items, total, len(representative)


class SampleExistsError(RuntimeError):
    pass


def write_sample(
    sample: AuditSample, directory: Path, name: str = "audit-50"
) -> tuple[Path, Path, bool]:
    """Write ``<name>.json`` and a blank worksheet. Returns (sample, worksheet, worksheet_written).

    Annotations are irreplaceable: an existing worksheet is never overwritten. An existing
    sample file may only be regenerated byte-identical; a different one raises.
    """
    directory.mkdir(parents=True, exist_ok=True)
    sample_path = directory / f"{name}.json"
    content = sample.model_dump_json(indent=2, exclude_none=True) + "\n"
    if sample_path.exists() and sample_path.read_text(encoding="utf-8") != content:
        raise SampleExistsError(f"{sample_path} exists with different content; refusing")
    sample_path.write_text(content, encoding="utf-8")
    worksheet = directory / "worksheet.csv"
    if worksheet.exists():
        return sample_path, worksheet, False
    with worksheet.open("x", encoding="utf-8", newline="") as fh:  # "x": never truncate
        writer = csv.writer(fh)
        writer.writerow(WORKSHEET_COLUMNS)
        for item in sample.items:
            r = item.record
            writer.writerow([item.audit_id, r.gbif_id, r.county, r.locality])
    return sample_path, worksheet, True


def load_sample(path: Path) -> AuditSample:
    return AuditSample.model_validate_json(path.read_text(encoding="utf-8"))


def run_system(
    sample: AuditSample,
    index: Path,
    system: str,
    make_extractor: Callable[[Gazetteer], Extractor],
    note: str,
    limit: int = 5,
    meta: dict[str, Any] | None = None,
    extents: ExtentStore | None = None,
) -> dict[str, Any]:
    """Run one extractor + retrieval + uncertainty policy on every audited record.

    Only the model-input allowlist reaches the extractor. A categorized extraction failure is
    recorded for that record and the run continues. With ``extents``, the top candidate's
    reviewed extent (if any) goes into its proposal, and each row records the extent's source.
    """
    from localitylens.extract.llm_client import ModelCallError
    from localitylens.extract.validate import VALIDATION_VERSION, Severity
    from localitylens.gazetteer.keys import CORE_KEY_VERSION
    from localitylens.geo import uncertainty as policy
    from localitylens.geo.georeference import propose
    from localitylens.pipeline.interpret import interpret

    rows: list[dict[str, Any]] = []
    with Gazetteer(index) as gaz:
        extractor = make_extractor(gaz)
        gazetteer_snapshot = gaz.snapshot_id
        for item in sample.items:
            model_input = item.record.model_input()  # the allowlist is the only door in
            row: dict[str, Any] = {
                "audit_id": item.audit_id,
                "locality": model_input.locality,
                "county": model_input.county,
            }
            started = time.perf_counter()
            try:
                result = interpret(
                    model_input.locality,
                    extractor,
                    gaz,
                    supplied_county=model_input.county or None,
                    limit=limit,
                )
            except ModelCallError as exc:
                row |= {"relation": None, "reference": None, "validation_errors": [],
                        "retrieval": None, "candidates": 0, "candidate_ids": [],
                        "interpretation": None, "top_candidate": None,
                        "proposal": f"failed:{exc.category.value}",
                        "radius_lower_bound_m": None, "radius_m": None}  # fmt: skip
                if extents is not None:
                    row["extent"] = None
                _add_trace(row, extractor, started)
                rows.append(row)
                continue
            interp = result.validation.interpretation
            retrieval = result.retrieval
            top = retrieval.candidates[0] if retrieval and retrieval.candidates else None
            extent = extents.get(top.feature_id) if extents is not None and top else None
            proposal = propose(interp, top, extent) if interp is not None else None
            row |= {
                "relation": result.extraction.relation.value,
                "reference": (
                    interp.reference_feature.name
                    if interp is not None and interp.reference_feature is not None
                    else None
                ),
                "validation_errors": [
                    i.code.value for i in result.validation.issues if i.severity is Severity.ERROR
                ],
                "retrieval": retrieval.outcome.value if retrieval else None,
                "candidates": len(retrieval.candidates) if retrieval else 0,
                "candidate_ids": [c.feature_id for c in retrieval.candidates] if retrieval else [],
                "interpretation": None if interp is None else _summary(interp),
                "top_candidate": None
                if top is None
                else {
                    "feature_id": top.feature_id,
                    "name": top.official_name,
                    "class": top.feature_class,
                    "county": top.county_name,
                    "match": top.match_kind.value,
                },
                "proposal": proposal.outcome.value if proposal else "invalid_extraction",
                "radius_lower_bound_m": (
                    round(proposal.radius_lower_bound_m)
                    if proposal and proposal.radius_lower_bound_m is not None
                    else None
                ),
                "radius_m": round(proposal.radius_m) if proposal and proposal.radius_m else None,
            }
            if extents is not None:
                row["extent"] = _extent_source(proposal)
            _add_trace(row, extractor, started)
            rows.append(row)
    return {
        "audit_version": sample.audit_version,
        "system": system,
        "extractor_version": extractor.version,
        "gazetteer_snapshot": gazetteer_snapshot,
        "specimen_snapshot": sample.snapshot_id,
        "uncertainty_policy": policy.POLICY_ID,
        "validation_version": VALIDATION_VERSION,
        "core_key_version": CORE_KEY_VERSION,
        "seed": sample.seed,
        **(meta or {}),
        **({"extent_store": extents.summary()} if extents is not None else {}),
        "note": note if extents is None else note.replace("no extent was supplied", _EXTENTS_NOTE),
        "counts": {
            "relation": dict(Counter(str(r["relation"]) for r in rows).most_common()),
            "retrieval": dict(Counter(str(r["retrieval"]) for r in rows).most_common()),
            "proposal": dict(Counter(str(r["proposal"]) for r in rows).most_common()),
        },
        "records": rows,
    }


_EXTENTS_NOTE: Final = "extents come from the reviewed-extent store where it has one"


def _extent_source(proposal: Any) -> str | None:
    """``reviewed`` / ``class_default`` when the proposal used an extent, else ``None``."""
    if proposal is None:
        return None
    for c in proposal.components:
        if c.name.value == "extent" and c.metres is not None:
            return str(c.rule.split(":", 1)[0])
    return None


def _summary(interp: Interpretation) -> dict[str, Any]:
    """The critical interpretation fields that scoring compares (CLAUDE.md §17)."""
    d = interp.distance
    return {
        "relation": interp.relation.value,
        "distance": d.quantity.value if d is not None else None,
        "unit": d.unit.value if d is not None and d.unit is not None else None,
        "direction": interp.direction.point.value if interp.direction is not None else None,
        "qualifiers": sorted({q.kind.value for q in interp.qualifiers}),
    }


def _add_trace(row: dict[str, Any], extractor: Extractor, started: float) -> None:
    trace = getattr(extractor, "last_trace", None)
    if trace is None:
        return  # deterministic rules: no model call to describe
    row["trace"] = {
        "prompt_sha256": trace.prompt_sha256,
        "prompt_tokens": trace.prompt_tokens,
        "completion_tokens": trace.completion_tokens,
        "attempts": trace.attempts,
        "errors": trace.errors,
        "model_seconds": round(trace.seconds, 2),
        "record_seconds": round(time.perf_counter() - started, 2),
    }


_NOTE_TAIL: Final = (
    "the top candidate is the system's ranking, not a reviewed choice, and no extent was supplied."
)


def run_rules(
    sample: AuditSample, index: Path, limit: int = 5, extents: ExtentStore | None = None
) -> dict[str, Any]:
    from localitylens.baseline.rules import Lexicon, RulesExtractor

    return run_system(
        sample,
        index,
        "rules",
        lambda gaz: RulesExtractor(Lexicon(gaz.county_names(), gaz.name_keys())),
        "System output only. Correctness needs the owner's annotations; the top candidate is "
        "the rules ranking, not a reviewed choice, and no extent was supplied.",
        limit,
        extents=extents,
    )


def run_llm(
    sample: AuditSample,
    index: Path,
    client: ModelClient,
    release: ReleaseManifest,
    limit: int = 5,
    server: dict[str, Any] | None = None,
    extents: ExtentStore | None = None,
) -> dict[str, Any]:
    from localitylens.extract.llm import LLMExtractor

    meta = {
        "model": f"{release.model.id}@{release.model.upstream_revision[:12]}",
        "gguf": f"{release.model.gguf_file} sha256={release.model.gguf_sha256}",
        "prompt": f"{release.prompt.version} sha256={release.prompt.sha256}",
        "generation": release.generation.model_dump(),
        "server": server or {},
    }
    return run_system(
        sample,
        index,
        "llm",
        lambda _gaz: LLMExtractor(client, release),
        "System output only. Correctness needs the owner's annotations; " + _NOTE_TAIL,
        limit,
        meta,
        extents,
    )


_TITLES: Final = {
    "rules": "rules baseline",
    "llm": "LLM extraction",
    "hybrid": "rules first, LLM fallback",
}
_HEADINGS: Final = {"audit-50": "50-record audit"}


def sample_label(sample: AuditSample) -> str:
    """File prefix and title for a sample's reports: ``audit-50`` or the dev sample's name."""
    return sample.name or "audit-50"


def extents_suffix(report: dict[str, Any]) -> str:
    """``-extents`` for a run that used the reviewed-extent store, so it never overwrites the
    run without it."""
    return "-extents" if "extent_store" in report else ""


def write_report(
    report: dict[str, Any], directory: Path, label: str = "audit-50"
) -> tuple[Path, Path]:
    directory.mkdir(parents=True, exist_ok=True)
    stem = f"{label}-{report['extractor_version']}{extents_suffix(report)}"
    json_path = directory / f"{stem}.json"
    json_path.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n", "utf-8")
    md = [
        f"# {_HEADINGS.get(label, label)}: {_TITLES.get(report['system'], report['system'])} "
        f"(`{report['extractor_version']}`)",
        "",
        f"Specimens `{report['specimen_snapshot']}` · gazetteer `{report['gazetteer_snapshot']}` "
        f"· policy `{report['uncertainty_policy']}` · seed `{report['seed']}`",
        "",
        f"> {report['note']}",
        "",
    ]
    for name, counts in report["counts"].items():
        md += [f"**{name}**: " + " · ".join(f"`{k}` {v}" for k, v in counts.items()), ""]
    md += [
        "| id | locality | relation | reference | retrieval | top candidate | proposal |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in report["records"]:
        top = r["top_candidate"]
        cand = f"{top['name']} ({top['class']}, {top['county']}, {top['match']})" if top else ""
        loc = r["locality"].replace("|", "\\|")
        md.append(
            f"| {r['audit_id']} | {loc} | {r['relation']} | {r['reference'] or ''} | "
            f"{r['retrieval'] or ''} | {cand} | {r['proposal'] or ''} |"
        )
    md_path = directory / f"{stem}.md"
    md_path.write_text("\n".join(md) + "\n", encoding="utf-8")
    return json_path, md_path
